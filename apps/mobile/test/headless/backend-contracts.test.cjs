const assert = require('node:assert/strict');
const { Backend, LEADER, PEER, GROUP_ID } = require('./backend.cjs');
const b = new Backend(() => {});
const table = (name, steps, userId = LEADER) => b.execute('contract', { kind: 'table', name, steps, userId });
const rpc = (name, args, userId = LEADER) => b.execute('contract', { kind: 'rpc', name, args, steps: [], userId });
assert.equal(table('profiles', [['select', '*'], ['eq', 'id', LEADER], ['maybeSingle']]).data.nickname, 'Leader');
assert.equal(table('profiles', [['select', '*'], ['eq', 'id', 'missing'], ['maybeSingle']]).data, null);
assert.equal(table('profiles', [['update', { nickname: 'Renamed' }], ['eq', 'id', LEADER], ['select', 'id'], ['maybeSingle']]).data.id, LEADER);
assert.equal(b.snapshot(GROUP_ID).profiles.find(p => p.id === LEADER).nickname, 'Renamed');
assert.equal(table('profiles', [['update', { nickname: 'Stolen' }], ['eq', 'id', PEER]]).error.code, '42501');
assert.equal(table('memberships', [['select', 'group_id, role'], ['eq', 'user_id', LEADER]]).data[0].group_id, GROUP_ID);
assert.equal(rpc('get_premium_projection', { p_group_id: GROUP_ID }).data.personalPremiumActive, false);
assert.equal(rpc('join_group', { p_code: 'BAD' }).error.code, 'P0002');
const group = rpc('create_group', { p_name: 'New group' }).data;
assert.equal(rpc('join_group', { p_code: group.invite_code }, PEER).data.id, group.id);
assert.equal(b.memberships.find(m => m.group_id === group.id && m.user_id === PEER).role, 'follower');
table('memberships', [['delete'], ['eq', 'user_id', PEER], ['in', 'group_id', [group.id]]], PEER);
assert.deepEqual(table('memberships', [['select', 'group_id'], ['eq', 'user_id', PEER], ['in', 'group_id', [group.id]]], PEER).data, []);
assert.throws(() => table('profiles', [['select', 'secret']]), /Unknown profiles selection/);
assert.throws(() => rpc('invented_rpc', {}), /Unsupported backend RPC/);
assert.throws(() => table('invented_table', [['select', '*']]), /Unsupported backend table/);
console.log('Backend bootstrap contracts passed');
